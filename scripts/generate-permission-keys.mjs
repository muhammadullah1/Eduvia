/**
 * Generates, from the API permission catalog (Eduvia-Api/constants/permissions.js), the single
 * source of truth for permission keys:
 *   - src/lib/permission-keys.generated.ts            the key union used by the app
 *   - src/test/default-role-permissions.generated.ts  each system role's default grants, for tests only
 *
 *   npm run gen:permissions                     (API checked out next to this repo)
 *   EDUVIA_API_DIR=/path/to/Eduvia-Api npm run gen:permissions
 */
import { writeFileSync } from "node:fs"
import { createRequire } from "node:module"
import { dirname, resolve } from "node:path"
import { fileURLToPath } from "node:url"

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..")
const apiDir = process.env.EDUVIA_API_DIR ?? resolve(root, "../Eduvia-Api")
const require = createRequire(import.meta.url)
const { PERMISSION_CATALOG, defaultPermissionsFor } = require(resolve(apiDir, "constants/permissions.js"))

const keys = PERMISSION_CATALOG.map((entry) => entry.key).sort()
const header = [
  "// Generated by scripts/generate-permission-keys.mjs from Eduvia-Api/constants/permissions.js.",
  "// Do not edit by hand: run `npm run gen:permissions` after the API catalog changes.",
  "",
]

const body = [
  ...header,
  "export const PERMISSION_KEYS = [",
  ...keys.map((key) => `  "${key}",`),
  "] as const",
  "",
  "export type PermissionKey = (typeof PERMISSION_KEYS)[number]",
  "",
].join("\n")

writeFileSync(resolve(root, "src/lib/permission-keys.generated.ts"), body)

const ROLES = ["super_admin", "operations_manager", "accountant", "teacher", "parent"]
const defaults = [
  ...header,
  'import type { Role } from "@/lib/auth"',
  'import type { PermissionKey } from "@/lib/permission-keys.generated"',
  "",
  "export const DEFAULT_ROLE_PERMISSIONS: Record<Role, PermissionKey[]> = {",
  ...ROLES.flatMap((role) => [
    `  ${role}: [`,
    ...[...defaultPermissionsFor(role)].sort().map((key) => `    "${key}",`),
    "  ],",
  ]),
  "}",
  "",
].join("\n")

writeFileSync(resolve(root, "src/test/default-role-permissions.generated.ts"), defaults)
